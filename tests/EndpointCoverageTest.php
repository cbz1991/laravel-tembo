<?php

namespace Cabuz\Tembo\Tests;

use Cabuz\Tembo\Resources\Resource;
use Cabuz\Tembo\Tembo;
use Illuminate\Http\Client\Request;
use Illuminate\Support\Facades\Http;
use ReflectionClass;
use ReflectionMethod;
use ReflectionNamedType;
use ReflectionUnionType;

/**
 * Calls every public resource method and checks each request against the
 * endpoints in Tembo's OpenAPI schema (tests/Fixtures/endpoints.json,
 * refreshed with bin/update-endpoints). Also keeps api.md in sync
 * (regenerate it with bin/api-reference).
 */
class EndpointCoverageTest extends TestCase
{
    /**
     * Endpoints deliberately not wrapped, with the reason.
     */
    private const NOT_WRAPPED = [
        'GET /oauth/context' => 'OAuth tokens only; API keys use authContext().',
        'GET /v1/live' => 'The WebSocket upgrade; opened by live()->connect().',
    ];

    /**
     * Methods that poll, dispatch jobs or open WebSockets instead of making one request.
     */
    private const SKIPPED_METHODS = ['wait', 'watch', 'connect', 'subscribe'];

    public function test_every_sdk_request_matches_a_documented_endpoint_and_every_endpoint_is_wrapped(): void
    {
        Http::fake(['*' => Http::response(['items' => [], 'nextCursor' => null, 'state' => ['current' => 'completed']])]);

        $tembo = $this->app->make(Tembo::class);
        $endpoints = $this->endpoints();
        $covered = [];
        $unknown = [];

        foreach ($this->resources($tembo) as $resource) {
            foreach ((new ReflectionClass($resource))->getMethods(ReflectionMethod::IS_PUBLIC) as $method) {
                if ($method->getDeclaringClass()->getName() === Resource::class
                    || $method->isConstructor()
                    || $this->returnsResource($method)
                    || in_array($method->getName(), self::SKIPPED_METHODS, true)) {
                    continue;
                }

                $before = count(Http::recorded());
                $method->invokeArgs($resource, $this->arguments($method));
                $requests = array_slice(Http::recorded()->all(), $before);

                $this->assertNotEmpty($requests, $resource::class.'::'.$method->getName().' sent no request.');

                foreach ($requests as [$request]) {
                    /** @var Request $request */
                    $endpoint = $this->match($request, $endpoints);

                    if ($endpoint === null) {
                        $unknown[] = $resource::class.'::'.$method->getName().' -> '.$request->method().' '.parse_url($request->url(), PHP_URL_PATH);
                    } else {
                        $covered[$endpoint] = true;
                    }
                }
            }
        }

        // Shortcuts that live on the client itself.
        $before = count(Http::recorded());
        $tembo->authContext();
        foreach (array_slice(Http::recorded()->all(), $before) as [$request]) {
            $covered[$this->match($request, $endpoints) ?? 'unknown'] = true;
        }

        $this->assertSame([], $unknown, 'Requests to endpoints that are not in the OpenAPI schema.');

        $missing = array_values(array_diff(array_keys($endpoints), array_keys($covered), array_keys(self::NOT_WRAPPED)));
        $this->assertSame([], $missing, 'Endpoints in the OpenAPI schema without an SDK method.');
    }

    public function test_api_md_lists_every_method(): void
    {
        Http::fake(['*' => Http::response(['items' => [], 'nextCursor' => null, 'state' => ['current' => 'completed'], 'ticket' => 't'])]);

        $tembo = $this->app->make(Tembo::class);
        $endpoints = $this->endpoints();

        $lines = [
            '# API reference',
            '',
            '<!-- Generated by bin/api-reference from the source code. Do not edit by hand. -->',
            '',
            'Every method of `laravel-tembo`, with the Tembo endpoint it calls. The structure and names',
            'follow the official [TypeScript SDK](https://github.com/tembo/sdk/blob/main/api.md).',
            'Call them on the `Tembo` facade or an injected `Cabuz\\Tembo\\Tembo`; list methods',
            'return a `CursorPage`, the others the decoded JSON as an array.',
            '',
            '## Client',
            '',
            '| Method | Endpoint |',
            '|---|---|',
        ];

        foreach ((new ReflectionClass($tembo))->getMethods(ReflectionMethod::IS_PUBLIC) as $method) {
            if (! $method->isStatic() && ! $method->isConstructor() && ! $this->returnsResource($method)) {
                $endpoint = in_array($method->getName(), ['me', 'authContext'], true) ? $this->endpointsCalled($tembo, $method, $endpoints) : '';
                $lines[] = '| `'.$this->signature($method).'` | '.$endpoint.' |';
            }
        }

        foreach ((new ReflectionClass($tembo))->getMethods(ReflectionMethod::IS_PUBLIC) as $method) {
            if ($this->returnsResource($method)) {
                $this->describe($method->invoke($tembo), $method->getName().'()', $endpoints, $lines);
            }
        }

        $markdown = implode("\n", $lines)."\n";
        $file = __DIR__.'/../api.md';

        if (getenv('UPDATE_API_REFERENCE')) {
            file_put_contents($file, $markdown);
        }

        $this->assertSame($markdown, (string) @file_get_contents($file), 'api.md is out of date; run bin/api-reference.');
    }

    /**
     * @param  array<string, string>  $endpoints
     * @param  list<string>  $lines
     */
    private function describe(Resource $resource, string $chain, array $endpoints, array &$lines): void
    {
        $lines[] = '';
        $lines[] = (substr_count($chain, '->') === 0 ? '## ' : '### ').'`'.$chain.'`';
        $lines[] = '';
        $lines[] = '| Method | Endpoint |';
        $lines[] = '|---|---|';
        $children = [];

        foreach ((new ReflectionClass($resource))->getMethods(ReflectionMethod::IS_PUBLIC) as $method) {
            if ($method->getDeclaringClass()->getName() === Resource::class || $method->isConstructor()) {
                continue;
            }

            if ($this->returnsResource($method)) {
                $children[$method->getName()] = $method->invoke($resource);

                continue;
            }

            $endpoint = match ($method->getName()) {
                'wait', 'watch' => 'polls `GET /v1/sessions/{sessionId}`',
                'connect' => 'WebSocket `GET /v1/live`',
                'subscribe' => '`POST /v1/live`, then WebSocket `GET /v1/live`',
                default => $this->endpointsCalled($resource, $method, $endpoints),
            };

            $lines[] = '| `'.$this->signature($method).'` | '.$endpoint.' |';
        }

        foreach ($children as $name => $child) {
            $this->describe($child, $chain.'->'.$name.'()', $endpoints, $lines);
        }
    }

    /**
     * @param  array<string, string>  $endpoints
     */
    private function endpointsCalled(object $target, ReflectionMethod $method, array $endpoints): string
    {
        $before = count(Http::recorded());
        $method->invokeArgs($target, $this->arguments($method));

        return implode(', ', array_unique(array_map(
            fn ($pair) => '`'.($this->match($pair[0], $endpoints) ?? 'unknown').'`',
            array_slice(Http::recorded()->all(), $before),
        )));
    }

    private function signature(ReflectionMethod $method): string
    {
        $parameters = array_map(function ($parameter) {
            $type = $parameter->getType();
            $text = ($type !== null ? str_replace(['Cabuz\\Tembo\\', 'Illuminate\\Http\\Client\\'], '', (string) $type).' ' : '').'$'.$parameter->getName();

            if ($parameter->isDefaultValueAvailable()) {
                $default = $parameter->getDefaultValue();
                $text .= ' = '.match (true) {
                    $default === [] => '[]',
                    $default === null => 'null',
                    is_bool($default) => $default ? 'true' : 'false',
                    is_string($default) => "'".$default."'",
                    default => (string) $default,
                };
            }

            return $text;
        }, $method->getParameters());

        $return = $method->getReturnType();
        $return = $return === null ? '' : ': '.preg_replace('#^(\\??).*\\\\#', '$1', (string) $return);

        return $method->getName().'('.implode(', ', $parameters).')'.$return;
    }

    /**
     * Every resource and sub-resource reachable from the client.
     *
     * @return list<resource>
     */
    private function resources(Tembo $tembo): array
    {
        $resources = [];

        foreach ((new ReflectionClass($tembo))->getMethods(ReflectionMethod::IS_PUBLIC) as $method) {
            if ($this->returnsResource($method)) {
                $resources[] = $method->invoke($tembo);
            }
        }

        $this->assertCount(19, $resources);

        for ($i = 0; $i < count($resources); $i++) {
            foreach ((new ReflectionClass($resources[$i]))->getMethods(ReflectionMethod::IS_PUBLIC) as $method) {
                if ($this->returnsResource($method)) {
                    $resources[] = $method->invoke($resources[$i]);
                }
            }
        }

        return $resources;
    }

    private function returnsResource(ReflectionMethod $method): bool
    {
        $type = $method->getReturnType();

        return $type instanceof ReflectionNamedType && is_subclass_of($type->getName(), Resource::class);
    }

    /**
     * @return list<mixed>
     */
    private function arguments(ReflectionMethod $method): array
    {
        $arguments = [];

        foreach ($method->getParameters() as $parameter) {
            if ($parameter->isOptional()) {
                break;
            }

            $type = $parameter->getType();
            $names = $type instanceof ReflectionUnionType
                ? array_map(fn ($t) => $t instanceof ReflectionNamedType ? $t->getName() : 'mixed', $type->getTypes())
                : [$type instanceof ReflectionNamedType ? $type->getName() : 'mixed'];

            $arguments[] = match (true) {
                in_array('string', $names, true) => 'id1',
                in_array('int', $names, true) => 1,
                in_array('array', $names, true) => [],
                in_array('mixed', $names, true) => 'contents',
                default => null,
            };
        }

        return $arguments;
    }

    /**
     * @return array<string, string> "METHOD /path/{param}" => regex
     */
    private function endpoints(): array
    {
        $list = json_decode((string) file_get_contents(__DIR__.'/Fixtures/endpoints.json'), true);
        $endpoints = [];

        // Literal paths first, so /v1/sessions/sources wins over /v1/sessions/{sessionId}.
        usort($list, fn ($a, $b) => substr_count($a, '{') <=> substr_count($b, '{'));

        foreach ($list as $endpoint) {
            [$verb, $path] = explode(' ', $endpoint, 2);
            $endpoints[$endpoint] = '#^'.$verb.' '.preg_replace('#\\\\\{[^/]+\\\\\}#', '[^/]+', preg_quote($path, '#')).'$#';
        }

        return $endpoints;
    }

    /**
     * @param  array<string, string>  $endpoints
     */
    private function match(Request $request, array $endpoints): ?string
    {
        $actual = $request->method().' '.parse_url($request->url(), PHP_URL_PATH);

        foreach ($endpoints as $endpoint => $pattern) {
            if (preg_match($pattern, $actual)) {
                return $endpoint;
            }
        }

        return null;
    }
}
